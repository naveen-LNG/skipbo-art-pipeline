#!/usr/bin/env python3
"""Read-only snapshot of the saved workflows on a ComfyUI server.

Pulls every workflow under the server's user `workflows/` folder, saves the raw
JSON, renders one Markdown file per workflow (pipeline, parameters, verbatim
prompts, notes) and optionally downloads the input images the workflows load.

Only GET requests are made. Nothing is queued, uploaded or modified.
Standard library only, so it runs the same on macOS, Windows and Linux:

    python tools/comfy_snapshot.py
    python tools/comfy_snapshot.py --server https://skipbo.comfyui.liquidnitro.games --images
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import sys
import urllib.parse
import urllib.request
from pathlib import Path

DEFAULT_SERVER = "https://skipbo.comfyui.liquidnitro.games"
ROOT = Path(__file__).resolve().parent.parent
WIDGET_TYPES = {"INT", "FLOAT", "STRING", "BOOLEAN", "COMBO"}
NOTE_TYPES = {"Note", "MarkdownNote"}


def get(server: str, path: str) -> bytes:
    req = urllib.request.Request(server.rstrip("/") + path, headers={"User-Agent": "comfy-snapshot/1"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def get_json(server: str, path: str):
    return json.loads(get(server, path))


def slugify(name: str) -> str:
    s = re.sub(r"\.json$", "", name.strip())
    s = re.sub(r"[^A-Za-z0-9]+", "-", s).strip("-").lower()
    return s or "workflow"


def widget_names(schema: dict | None) -> list[str]:
    """Names of a node's widgets, in the order ComfyUI stores widgets_values."""
    if not schema:
        return []
    names: list[str] = []
    for section in ("required", "optional"):
        for name, spec in schema.get("input", {}).get(section, {}).items():
            kind = spec[0]
            opts = spec[1] if len(spec) > 1 and isinstance(spec[1], dict) else {}
            if not (isinstance(kind, list) or kind in WIDGET_TYPES):
                continue
            names.append(name)
            if opts.get("control_after_generate") or (kind == "INT" and name in ("seed", "noise_seed")):
                names.append(f"{name} (after generate)")
            if opts.get("image_upload"):
                names.append("upload")
    return names


def fence(text: str, lang: str = "text") -> str:
    return f"~~~~{lang}\n{text.rstrip()}\n~~~~"


def render(name: str, meta: dict, wf: dict, schemas: dict, server: str, image_dir: str) -> str:
    nodes = sorted(wf.get("nodes", []), key=lambda n: n["id"])
    by_id = {n["id"]: n for n in nodes}
    links = {l[0]: l for l in wf.get("links", [])}
    modified = dt.datetime.fromtimestamp(meta.get("modified", 0), dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    out = [f"# {name.removesuffix('.json').strip()}", ""]
    out += [
        f"- **Server:** {server}",
        f"- **File:** `workflows/{name}` ({meta.get('size', '?')} bytes, last modified {modified})",
        f"- **Raw JSON:** [`originals/{name}`](originals/{urllib.parse.quote(name)})",
        f"- **Snapshot taken:** {dt.date.today().isoformat()} (read-only GET, nothing changed on the server)",
        "",
        "> Generated by `tools/comfy_snapshot.py`. Re-run it to refresh; edit the hand-written notes in `workflows/README.md` instead.",
        "",
    ]

    groups = [g.get("title") for g in wf.get("groups", []) if g.get("title")]
    if groups:
        out += ["**Groups in the canvas:** " + ", ".join(f"`{g}`" for g in groups), ""]

    out += ["## Pipeline", "", "| id | node | wired inputs |", "|---|---|---|"]
    for n in nodes:
        if n["type"] in NOTE_TYPES:
            continue
        wired = []
        for inp in n.get("inputs", []):
            l = links.get(inp.get("link"))
            if l:
                src = by_id.get(l[1], {})
                wired.append(f"{inp['name']} ← #{l[1]} {src.get('type', '?')}")
        title = f" «{n['title']}»" if n.get("title") else ""
        bypass = " *(bypassed)*" if n.get("mode") == 4 else (" *(muted)*" if n.get("mode") == 2 else "")
        out.append(f"| {n['id']} | `{n['type']}`{title}{bypass} | {'<br>'.join(wired) or '—'} |")
    out.append("")

    prompts: list[tuple[str, str]] = []
    images: list[str] = []
    out += ["## Parameters", ""]
    for n in nodes:
        if n["type"] in NOTE_TYPES:
            continue
        values = n.get("widgets_values")
        if not values or not isinstance(values, list):
            continue
        names = widget_names(schemas.get(n["type"]))
        if len(names) != len(values):
            names = names[: len(values)] + [f"widget {i}" for i in range(len(names), len(values))]
        rows = []
        for key, val in zip(names, values):
            if isinstance(val, str) and ("\n" in val or len(val) > 120):
                prompts.append((f"#{n['id']} {n['type']} · {key}", val))
                val = "*(long text — see Prompts below)*"
            elif n["type"] == "LoadImage" and key == "image":
                images.append(val)
                val = f"`{val}`"
            else:
                val = f"`{json.dumps(val, ensure_ascii=False)}`"
            rows.append(f"| {key} | {val} |")
        if rows:
            out += [f"**#{n['id']} `{n['type']}`**", "", "| widget | value |", "|---|---|", *rows, ""]

    if prompts:
        out += ["## Prompts (verbatim)", ""]
        seen: set[str] = set()
        for label, text in prompts:
            if text in seen:
                out += [f"### {label}", "", "*Identical to the prompt above (linked primitive).*", ""]
                continue
            seen.add(text)
            out += [f"### {label}", "", f"{len(text.split())} words, {len(text)} characters.", "", fence(text), ""]

    notes = [n for n in nodes if n["type"] in NOTE_TYPES]
    if notes:
        out += ["## Notes on the canvas", ""]
        for n in notes:
            text = (n.get("widgets_values") or [""])[0]
            out += [f"### {n.get('title') or n['type']} (#{n['id']})", "", fence(text, "markdown" if n["type"] == "MarkdownNote" else "text"), ""]

    if images:
        out += ["## Input images", ""]
        for img in images:
            local = Path(image_dir) / img
            exists = (ROOT / local).exists()
            link = f"[`{img}`](../{urllib.parse.quote(local.as_posix())})" if exists else f"`{img}` (not downloaded — run with `--images`)"
            out.append(f"- {link}")
        out.append("")
    return "\n".join(out)


def compact_history(history: dict) -> list[dict]:
    """One row per job: prompt text, model, sampler settings, inputs and outputs."""
    rows = []
    for pid, entry in history.items():
        prompt = entry["prompt"]
        graph = prompt[2]
        extra = prompt[3] if len(prompt) > 3 else {}
        status = entry.get("status", {})
        stamps = {m[0]: m[1].get("timestamp") for m in status.get("messages", [])}
        row = {
            "prompt_id": pid,
            "client_id": extra.get("client_id"),
            "start_ms": stamps.get("execution_start"),
            "end_ms": stamps.get("execution_success") or stamps.get("execution_error"),
            "status": status.get("status_str"),
            "nodes": sorted({n["class_type"] for n in graph.values()}),
            "inputs": [],
            "outputs": [],
        }
        for n in graph.values():
            i, t = n["inputs"], n["class_type"]
            scalars = {k: v for k, v in i.items() if not isinstance(v, list)}
            if t == "CLIPTextEncode":
                row["text"] = i.get("text")
            elif t.startswith("NanoBanana") and "prompt" in i:
                row["text"] = i.get("prompt")
                row["nano_banana"] = {k: v for k, v in scalars.items() if k != "prompt"}
            elif t == "KSampler":
                row["ksampler"] = scalars
            elif t == "UNETLoader":
                row["unet"] = i.get("unet_name")
            elif t == "LoraLoaderModelOnly":
                row.setdefault("loras", []).append([i.get("lora_name"), i.get("strength_model")])
            elif t == "LoadImage":
                row["inputs"].append(i.get("image"))
            elif t == "SaveImage":
                row["save_prefix"] = i.get("filename_prefix")
            elif t == "easy imageRemBg":
                row["rembg"] = i.get("rem_mode")
                row["save_prefix"] = i.get("save_prefix")
            elif t == "GrowMask":
                row["grow_mask"] = i.get("expand")
        for out in (entry.get("outputs") or {}).values():
            for im in out.get("images", []):
                sub = im.get("subfolder")
                row["outputs"].append(f"{sub}/{im['filename']}" if sub else im["filename"])
        rows.append(row)
    rows.sort(key=lambda r: r["start_ms"] or 0)
    return rows


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--server", default=DEFAULT_SERVER)
    ap.add_argument("--out", default=str(ROOT / "workflows"), help="where to write .md and originals/")
    ap.add_argument("--images", action="store_true", help="also download the input images the workflows load")
    ap.add_argument("--image-dir", default="references/style-refs", help="image folder, relative to the repo root")
    ap.add_argument("--history", action="store_true",
                    help="also save the server's job history (it only keeps ~3 days) as JSONL")
    args = ap.parse_args()

    if args.history:
        rows = compact_history(get_json(args.server, "/history?max_items=100000"))
        if rows:
            first = dt.datetime.fromtimestamp(rows[0]["start_ms"] / 1000, dt.timezone.utc).date()
            last = dt.datetime.fromtimestamp(rows[-1]["start_ms"] / 1000, dt.timezone.utc).date()
            path = ROOT / "references" / "usage-reports" / f"job-history-{first}_to_{last}.jsonl"
            path.parent.mkdir(parents=True, exist_ok=True)
            with path.open("w", encoding="utf-8") as f:
                for row in rows:
                    f.write(json.dumps(row, ensure_ascii=False) + "\n")
            print(f"{len(rows)} history jobs -> {path.relative_to(ROOT)}")

    out = Path(args.out)
    (out / "originals").mkdir(parents=True, exist_ok=True)
    listing = get_json(args.server, "/api/userdata?dir=workflows&recurse=true&split=false&full_info=true")
    print(f"{len(listing)} workflows on {args.server}")

    workflows = {}
    for meta in listing:
        name = meta["path"]
        raw = get(args.server, "/api/userdata/" + urllib.parse.quote("workflows/" + name, safe=""))
        (out / "originals" / name).write_bytes(raw)
        workflows[name] = (meta, json.loads(raw))

    types = {n["type"] for _, wf in workflows.values() for n in wf.get("nodes", [])} - NOTE_TYPES
    schemas = {}
    for t in sorted(types):
        try:
            schemas.update(get_json(args.server, "/object_info/" + urllib.parse.quote(t)))
        except Exception as e:  # custom node removed from the server, etc.
            print(f"  ! no schema for {t}: {e}", file=sys.stderr)

    if args.images:
        img_dir = ROOT / args.image_dir
        img_dir.mkdir(parents=True, exist_ok=True)
        for _, wf in workflows.values():
            for n in wf.get("nodes", []):
                if n["type"] == "LoadImage" and n.get("widgets_values"):
                    fname = n["widgets_values"][0]
                    try:
                        data = get(args.server, "/view?type=input&filename=" + urllib.parse.quote(fname))
                        (img_dir / fname).write_bytes(data)
                        print(f"  image {fname} ({len(data)} bytes)")
                    except Exception as e:
                        print(f"  ! image {fname}: {e}", file=sys.stderr)

    for name, (meta, wf) in workflows.items():
        md = render(name, meta, wf, schemas, args.server, args.image_dir)
        path = out / f"{slugify(name)}.md"
        path.write_text(md, encoding="utf-8")
        print(f"  wrote {path.relative_to(ROOT) if path.is_relative_to(ROOT) else path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
